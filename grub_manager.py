#!/usr/bin/python3
"""Discover GRUB entries and manage a separate custom.cfg."""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import subprocess
import tempfile
from dataclasses import dataclass

from i18n import _ as tr


BOOT_GRUB = Path("/boot/grub")
MARKER = "# Generated by GOS GRUB Manager\n"
WINDOWS_MARKER = "# GOS Windows UEFI\n"
SAFE_NAME = re.compile(r"^[A-Za-z0-9._-]+\.cfg$")
SOURCE_LINE = re.compile(r'^source "\$\{prefix\}/custom/([A-Za-z0-9._-]+\.cfg)"$')
DISABLED_LINE = re.compile(r"^# GOS disabled: ([A-Za-z0-9._-]+\.cfg)$")
UUID = re.compile(r"^[A-Za-z0-9-]+$")
VARIABLE = re.compile(r"\$(?:\{([A-Za-z_][A-Za-z0-9_]*)\}|([A-Za-z_][A-Za-z0-9_]*))")
DEFINITION = re.compile(r"^\s*function\s+([A-Za-z_][A-Za-z0-9_]*)\s*\{", re.MULTILINE)
ENTRY = re.compile(r"^\s*menuentry\s+", re.MULTILINE)
BOOT_COMMAND = re.compile(r"^\s*(?:linux(?:efi|16)?|chainloader)\s+", re.MULTILINE)
LINUX_GFX_MODE = re.compile(
    r"(?m)^### BEGIN /etc/grub\.d/10_linux ###\r?\n"
    r"[ \t]*function[ \t]+gfxmode[ \t]*\{[ \t]*\r?\n"
    r'[ \t]*set[ \t]+gfxpayload="\$\{1\}"[ \t]*\r?\n'
    r"[ \t]*\}[ \t]*\r?\n"
    r"[ \t]*set[ \t]+linux_gfx_mode=(['\"]?)([A-Za-z0-9_,.-]+)\1[ \t]*\r?\n"
    r"[ \t]*export[ \t]+linux_gfx_mode[ \t]*$"
)
BUILTIN_VARIABLES = {
    "root", "prefix", "grub_platform", "feature_all_video_module",
    "feature_menuentry_id", "feature_platform_search_hint",
}
FILESYSTEMS = {
    "ext2": "ro,noload,nosuid,nodev,noexec",
    "ext3": "ro,noload,nosuid,nodev,noexec",
    "ext4": "ro,noload,nosuid,nodev,noexec",
    "btrfs": "ro,rescue=nologreplay,subvolid=5,nosuid,nodev,noexec",
    "xfs": "ro,norecovery,nosuid,nodev,noexec",
    "vfat": "ro,nosuid,nodev,noexec",
    "exfat": "ro,nosuid,nodev,noexec",
    "ntfs": "ro,nosuid,nodev,noexec",
    "ntfs3": "ro,nosuid,nodev,noexec",
}


@dataclass(frozen=True)
class FoundConfig:
    device: str
    location: str
    name: str
    filename: str
    content: str
    entry_count: int


@dataclass
class ScanResult:
    configs: list[FoundConfig]
    warnings: list[str]


def command(*args: str) -> str:
    result = subprocess.run(args, text=True, capture_output=True, check=False)
    if result.returncode:
        raise RuntimeError(f"{args[0]}: {result.stderr.strip() or result.stdout.strip() or tr('Error')}")
    return result.stdout


def _mount_filesystem(fstype: str, path: str, mountpoint: Path) -> None:
    options = FILESYSTEMS[fstype]
    try:
        command("mount", "-t", fstype, "-o", options, "--", path, str(mountpoint))
    except RuntimeError as first_error:
        if fstype != "btrfs":
            raise
        legacy_options = options.replace("rescue=nologreplay", "nologreplay")
        try:
            command("mount", "-t", fstype, "-o", legacy_options, "--", path, str(mountpoint))
        except (OSError, RuntimeError) as second_error:
            raise RuntimeError(f"{first_error}\n{second_error}") from second_error


def _block(text: str, start: int) -> tuple[str, int]:
    """Read a GRUB brace block, ignoring braces in quotes, comments and ${...}."""
    quote = ""
    escaped = False
    comment = False
    depth = 0
    opened = False
    variable = False
    opening = -1
    for i in range(start, len(text)):
        c = text[i]
        if comment:
            if c == "\n":
                comment = False
            continue
        if escaped:
            escaped = False
            continue
        if c == "\\" and quote != "'":
            escaped = True
            continue
        if quote:
            if c == quote:
                quote = ""
            continue
        if c in "'\"":
            quote = c
            continue
        if c == "#":
            comment = True
            continue
        if variable:
            if c == "}":
                variable = False
            continue
        if c == "{" and i > 0 and text[i - 1] == "$":
            variable = True
            continue
        if c == "{":
            depth += 1
            if not opened:
                opening = i - start
            opened = True
        elif c == "}":
            depth -= 1
            if opened and depth == 0:
                return text[start:i + 1], opening
            if depth < 0:
                break
    raise ValueError(tr("Unterminated GRUB block"))


def _definitions(text: str) -> dict[str, str]:
    result = {}
    for match in DEFINITION.finditer(text):
        result[match.group(1)] = _block(text, match.start())[0]
    return result


def _called_functions(text: str, definitions: dict[str, str]) -> set[str]:
    return {
        name for name in definitions
        if re.search(r"(?m)^\s*" + re.escape(name) + r"(?:\s|;|$)", text)
    }


def extract_entries(text: str, filesystem_uuid: str,
                    filesystem_type: str | None = None) -> tuple[str, str, int, list[str]]:
    """Extract independent boot entries; unsupported external variables are rejected."""
    if not UUID.fullmatch(filesystem_uuid):
        raise ValueError(tr("Filesystem UUID is missing or invalid"))
    definitions = _definitions(text)
    gfx_modes = list(LINUX_GFX_MODE.finditer(text))
    gfx_assignments = re.findall(
        r"(?<![A-Za-z0-9_])(?:(?:set[ \t]+)?linux_gfx_mode=|unset[ \t]+linux_gfx_mode\b)",
        text,
    )
    gfx_mode = None
    if len(gfx_modes) == len(gfx_assignments) == 1:
        later_text = text[gfx_modes[0].end():]
        if not re.search(r"(?<![A-Za-z0-9_])load_env(?=[ \t;\r\n]|$)", later_text):
            gfx_mode = gfx_modes[0].group(2)
    entries = []
    warnings = []
    first_name = ""
    for match in ENTRY.finditer(text):
        block, brace = _block(text, match.start())
        if not BOOT_COMMAND.search(block):
            continue
        header = block[:brace].strip()
        try:
            parts = shlex.split(header)
            name = parts[1]
        except (ValueError, IndexError):
            warnings.append(tr("An entry without a readable name was skipped."))
            continue
        if (re.search(r"(?m)^\s*chainloader\s+", block)
                and ("windows" in name.casefold() or "bootmgfw.efi" in block.casefold())):
            warnings.append(tr("{name}: Windows chainloader is checked separately against the BCD.").format(name=name))
            continue
        block = block.replace("$menuentry_id_option", "--id").replace(
            "${menuentry_id_option}", "--id"
        )
        # Recalculate after replacing a potentially longer header variable.
        _, brace = _block(block, 0)
        fs_module = {
            "ext2": "ext2", "ext3": "ext2", "ext4": "ext2", "btrfs": "btrfs",
            "xfs": "xfs", "vfat": "fat", "exfat": "exfat",
            "ntfs": "ntfs", "ntfs3": "ntfs",
        }.get(filesystem_type)
        modules = ""
        if fs_module:
            modules = f"\n    insmod part_gpt\n    insmod part_msdos\n    insmod {fs_module}"
        block = (
            block[:brace + 1] + modules
            + f"\n    if search --no-floppy --fs-uuid --set=root {filesystem_uuid}; then\n"
            + block[brace + 1:-1]
            + "\n    else\n        echo 'GOS: Filesystem not found.'\n    fi\n}"
        )
        needed = _called_functions(block, definitions)
        pending = set(needed)
        while pending:
            function = pending.pop()
            dependencies = _called_functions(definitions[function], definitions) - needed
            needed.update(dependencies)
            pending.update(dependencies)
        combined = "\n".join(definitions[n] for n in sorted(needed)) + "\n" + block
        assigned = set(re.findall(
            r"(?m)^\s*(?:set\s+)?([A-Za-z_][A-Za-z0-9_]*)=", combined
        ))
        used = {a or b for a, b in VARIABLE.findall(combined)}
        unsupported = used - assigned - BUILTIN_VARIABLES
        if "linux_gfx_mode" in unsupported and gfx_mode is not None:
            block = block[:brace + 1] + f"\n    set linux_gfx_mode={gfx_mode}" + block[brace + 1:]
            combined = "\n".join(definitions[n] for n in sorted(needed)) + "\n" + block
            unsupported.remove("linux_gfx_mode")
        if unsupported:
            warnings.append(
                tr("{name}: external GRUB variables cannot be resolved: {variables}").format(
                    name=name, variables=", ".join(sorted(unsupported)))
            )
            continue
        # Give copied functions unique names so they do not replace the host's functions.
        suffix = hashlib.sha256((filesystem_uuid + name + block).encode()).hexdigest()[:12]
        for function in sorted(needed, key=len, reverse=True):
            replacement = f"gos_{suffix}_{function}"
            combined = re.sub(
                r"(?m)^(\s*(?:function\s+)?)" + re.escape(function) + r"(?=\s|[;{]|$)",
                lambda m: m.group(1) + replacement, combined,
            )
        entries.append(combined.strip())
        if not first_name:
            first_name = name
    return "\n\n".join(entries) + "\n", first_name, len(entries), warnings


def _safe_file(root: Path, relative: str) -> Path | None:
    path = root / relative
    resolved_root = root.resolve()
    resolved = path.resolve()
    if not resolved.is_relative_to(resolved_root):
        raise ValueError(tr("Path escapes the filesystem: {path}").format(path=path))
    return path if path.is_file() else None


def _walk_devices(devices: list[dict]) -> list[dict]:
    result = []
    for device in devices:
        result.append(device)
        result.extend(_walk_devices(device.get("children") or []))
    return result


def scan() -> ScanResult:
    data = json.loads(command("lsblk", "--json", "--paths", "--output",
                              "PATH,TYPE,FSTYPE,UUID,PARTUUID,PTUUID,MOUNTPOINTS"))
    configs: list[FoundConfig] = []
    warnings: list[str] = []
    seen_devices: set[str] = set()
    seen_files: set[tuple[int, int]] = set()
    try:
        host_config = (BOOT_GRUB / "grub.cfg").stat()
    except FileNotFoundError:
        pass
    else:
        seen_files.add((host_config.st_dev, host_config.st_ino))
    devices = _walk_devices(data["blockdevices"])
    unique_devices = []
    for device in devices:
        path = device["path"]
        if path in seen_devices:
            continue
        seen_devices.add(path)
        unique_devices.append(device)
        fstype = device.get("fstype")
        if not fstype or fstype == "swap":
            continue
        mountpoints = [Path(p) for p in (device.get("mountpoints") or [])
                       if p and p.startswith("/")]
        if fstype not in FILESYSTEMS:
            warnings.append(tr("{path}: filesystem {fstype} is not supported.").format(path=path, fstype=fstype))
            continue
        if not device.get("uuid"):
            warnings.append(tr("{path}: filesystem UUID is missing.").format(path=path))
            continue
        # For btrfs the existing mount may expose only a subvolume rather than @.
        needs_mount = not mountpoints or fstype == "btrfs"
        temp = Path(tempfile.mkdtemp(prefix="gos-grub-")) if needs_mount else None
        mounted = False
        try:
            if temp is not None:
                try:
                    _mount_filesystem(fstype, path, temp)
                except (OSError, RuntimeError) as exc:
                    warnings.append(f"{path}: {exc}")
                else:
                    mounted = True
                    mountpoints.append(temp)
            for root in mountpoints:
                for relative in ("boot/grub/grub.cfg", "@/boot/grub/grub.cfg", "grub/grub.cfg"):
                    try:
                        config = _safe_file(root, relative)
                        if config is None:
                            continue
                        stat = config.stat()
                        identity = (stat.st_dev, stat.st_ino)
                        if identity in seen_files:
                            continue
                        seen_files.add(identity)
                        text = config.read_text(encoding="utf-8")
                        # A mountpoint may itself contain a separately mounted /boot.
                        actual_uuid = command("findmnt", "-n", "-o", "UUID", "-T", str(config)).strip()
                        actual_fstype = command("findmnt", "-n", "-o", "FSTYPE", "-T", str(config)).strip()
                        content, name, count, entry_warnings = extract_entries(text, actual_uuid, actual_fstype)
                        warnings.extend(f"{path}: {w}" for w in entry_warnings)
                        if not count:
                            warnings.append(tr("{path}: {config}: no supported boot entries.").format(
                                path=path, config=config))
                            continue
                        slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")[:40] or "linux"
                        key = hashlib.sha256((actual_uuid + relative).encode()).hexdigest()[:10]
                        configs.append(FoundConfig(
                            path, relative, name, f"{slug}-{key}.cfg",
                            MARKER + content, count,
                        ))
                    except (OSError, UnicodeError, ValueError, RuntimeError) as exc:
                        warnings.append(f"{path}: {root / relative}: {exc}")
        except (OSError, RuntimeError) as exc:
            warnings.append(f"{path}: {exc}")
        finally:
            if mounted and temp is not None:
                try:
                    command("umount", "--", str(temp))
                except (OSError, RuntimeError) as exc:
                    # Preserve the mountpoint for manual recovery; do not hide the failure.
                    warnings.append(tr("WARNING: {path} is still mounted: {error}").format(path=temp, error=exc))
                else:
                    temp.rmdir()
            elif temp is not None:
                temp.rmdir()
    from windows_uefi import scan_windows
    windows_configs, windows_warnings = scan_windows(unique_devices)
    configs.extend(windows_configs)
    warnings.extend(windows_warnings)
    return ScanResult(configs, warnings)


def _validate(content: str) -> None:
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", suffix=".cfg") as file:
        file.write(content)
        file.flush()
        command("grub-script-check", file.name)


def _atomic_write(path: Path, content: str) -> None:
    fd, temporary = tempfile.mkstemp(prefix=".gos-grub-", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as file:
            file.write(content)
            file.flush()
            os.fsync(file.fileno())
        os.chmod(temporary, 0o644)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def existing_configuration(boot_grub: Path = BOOT_GRUB) -> tuple[list[str], set[str], str | None]:
    """Read the managed source order without changing any files."""
    custom = boot_grub / "custom"
    master = boot_grub / "custom.cfg"
    if boot_grub.is_symlink() or custom.is_symlink() or master.is_symlink():
        raise ValueError(tr("Symbolic links are not allowed as targets."))
    if custom.exists() and not custom.is_dir():
        raise ValueError(tr("The custom target path is not a directory."))
    names = set()
    if custom.exists():
        for existing in custom.glob("*.cfg"):
            if existing.is_symlink() or not existing.is_file() or not SAFE_NAME.fullmatch(existing.name):
                raise ValueError(tr("Unsupported file in custom: {name}").format(name=existing.name))
            names.add(existing.name)
    if not master.exists():
        return sorted(names), set(), None
    content = master.read_text(encoding="utf-8")
    if not content.startswith(MARKER):
        return sorted(names), set(), tr("An unmanaged custom.cfg exists; it will not be overwritten.")
    order = []
    disabled = set()
    for line in content[len(MARKER):].splitlines():
        match = SOURCE_LINE.fullmatch(line)
        if not match:
            match = DISABLED_LINE.fullmatch(line)
            if not match:
                return sorted(names), set(), tr("The managed custom.cfg contains unknown lines; "
                                                "the order cannot be read safely.")
            disabled.add(match.group(1))
        name = match.group(1)
        if name in order or name not in names:
            return sorted(names), set(), tr("Invalid or duplicate reference in custom.cfg: {name}").format(name=name)
        order.append(name)
    return order + sorted(names - set(order)), disabled, None


def existing_order(boot_grub: Path = BOOT_GRUB) -> tuple[list[str], str | None]:
    order, _, warning = existing_configuration(boot_grub)
    return order, warning


def managed_windows_names(boot_grub: Path = BOOT_GRUB) -> set[str]:
    custom = boot_grub / "custom"
    if boot_grub.is_symlink() or custom.is_symlink():
        raise ValueError(tr("Symbolic links are not allowed as targets."))
    if not custom.exists():
        return set()
    result = set()
    for path in custom.glob("windows-*.cfg"):
        if path.is_symlink() or not path.is_file() or not SAFE_NAME.fullmatch(path.name):
            raise ValueError(tr("Unsupported file in custom: {name}").format(name=path.name))
        if path.read_text(encoding="utf-8").startswith(MARKER + WINDOWS_MARKER):
            result.add(path.name)
    return result


def install(configs: list[FoundConfig], boot_grub: Path = BOOT_GRUB,
            order: list[str] | None = None,
            expected_existing: list[str] | None = None,
            disabled: set[str] | None = None,
            expected_disabled: set[str] | None = None) -> None:
    custom = boot_grub / "custom"
    master = boot_grub / "custom.cfg"
    existing, saved_disabled, warning = existing_configuration(boot_grub)
    if warning:
        raise ValueError(warning)
    if expected_existing is not None and existing != expected_existing:
        raise ValueError(tr("The saved order or files have changed. Please restart the application."))
    if expected_disabled is not None and saved_disabled != expected_disabled:
        raise ValueError(tr("The enabled files have changed. Please restart the application."))
    names = {config.filename for config in configs}
    if len(names) != len(configs):
        raise ValueError(tr("Duplicate target filenames; no files were written."))
    names.update(existing)
    if not names:
        raise ValueError(tr("No entries to save."))
    if order is None:
        order = existing + sorted(names - set(existing))
    if len(order) != len(names) or set(order) != names:
        raise ValueError(tr("The files have changed or the order is invalid. Please restart the application."))
    if disabled is None:
        disabled = saved_disabled
    if not disabled <= names:
        raise ValueError(tr("Invalid disabled configurations."))
    managed_windows = managed_windows_names(boot_grub)
    managed_windows.update(c.filename for c in configs
                           if c.content.startswith(MARKER + WINDOWS_MARKER))
    if not disabled <= managed_windows:
        raise ValueError(tr("Only managed Windows configurations can be disabled."))
    if custom.exists():
        for config in configs:
            target = custom / config.filename
            if target.exists() and not target.read_text(encoding="utf-8").startswith(MARKER):
                raise ValueError(tr("Unmanaged file will not be overwritten: {name}").format(name=target.name))
    for config in configs:
        if not SAFE_NAME.fullmatch(config.filename) or not config.content.startswith(MARKER):
            raise ValueError(tr("Invalid generated configuration."))
        _validate(config.content)
    if custom.exists():
        for name in names - {config.filename for config in configs} - disabled:
            _validate((custom / name).read_text(encoding="utf-8"))
    master_content = MARKER + "".join(
        f"# GOS disabled: {name}\n" if name in disabled
        else f'source "${{prefix}}/custom/{name}"\n' for name in order
    )
    _validate(master_content)
    custom.mkdir(mode=0o755, exist_ok=True)
    writes = [(custom / config.filename, config.content) for config in configs]
    writes.append((master, master_content))
    originals = {path: path.read_text(encoding="utf-8") if path.exists() else None
                 for path, _ in writes}
    written: list[Path] = []
    try:
        for path, content in writes:
            _atomic_write(path, content)
            written.append(path)
    except OSError as exc:
        errors = []
        for path in reversed(written):
            try:
                original = originals[path]
                if original is None:
                    path.unlink()
                else:
                    _atomic_write(path, original)
            except OSError as rollback_error:
                errors.append(f"{path}: {rollback_error}")
        if errors:
            raise RuntimeError(tr("Write failed: {error}; rollback failed: {details}").format(
                error=exc, details="; ".join(errors))) from exc
        raise
